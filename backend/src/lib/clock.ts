// Абстракция «сейчас». Сервисы и домен принимают Clock как зависимость,
// поэтому в тестах момент времени фиксируется (спека оперирует конкретными
// датами вроде «31 марта, 11:20», §5.2).

export interface Clock {
  now(): Date;
}

/** Системные часы — единственная реализация для продакшена. */
export const systemClock: Clock = {
  now: () => new Date(),
};

/** Часы с зафиксированным моментом для тестов. Возвращают свежую копию,
 *  чтобы мутация даты одним потребителем не повлияла на других. */
export function fixedClock(now: Date): Clock {
  return { now: () => new Date(now) };
}
